"""test_calibrate_tiered_slippage.py - proves calibrate_tiered_slippage.py's PURE rendering
functions (render_report / render_floor_reachable_section) on a small, hand-built per-symbol
DataFrame. No network calls (the live order-book fetch is calibrate_tiered_slippage.main(), a
one-off manual script -- not exercised here, same convention as test_tiered_slippage.py).

Added in the P1d fix pass (Architect review item 5: re-render tiered_slippage_calibration.md's
headline numbers restricted to the population each floor candidate can actually reach, plus an
informational flat-5bp comparison) -- this proves that rendering logic directly rather than just
trusting the regenerated .md file's numbers.
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

_THIS_DIR = Path(__file__).resolve().parent
_REPO_ROOT = _THIS_DIR.parent
for _p in (_REPO_ROOT, _THIS_DIR):
    if str(_p) not in sys.path:
        sys.path.insert(0, str(_p))

from calibrate_tiered_slippage import (  # noqa: E402
    FLAT_PRESET_BPS,
    render_floor_reachable_section,
    render_report,
    tier_label,
)


def _row(symbol, median_vol, assumed_bps, half_spread_bps, full_spread_bps=None):
    return dict(
        symbol=symbol,
        median_quote_volume_usd=median_vol,
        tier=tier_label(10_000_000.0 if median_vol is not None and median_vol >= 10_000_000.0
                        else (1_000_000.0 if median_vol is not None and median_vol >= 1_000_000.0 else 0.0)),
        assumed_bps=assumed_bps,
        half_spread_bps=half_spread_bps,
        full_spread_bps=full_spread_bps if full_spread_bps is not None else half_spread_bps * 2,
    )


def test_floor_reachable_section_restricts_population_and_computes_exceeding_rate():
    df = pd.DataFrame([
        _row("BIG/USD", 50_000_000.0, 5.0, 1.0),      # >=$10M tier, well inside assumed
        _row("MID/USD", 2_000_000.0, 20.0, 3.0),       # $1M-$10M tier, well inside assumed
        _row("THIN/USD", 500_000.0, 50.0, 60.0),       # <$1M tier, EXCEEDS its own assumed tier
        _row("DUST/USD", 5_000.0, 50.0, 9000.0),       # near-zero volume, way below any floor candidate
    ])

    section = render_floor_reachable_section(df, floors=(1_000_000.0, 100_000.0))

    # $1M-reachable population is BIG + MID only (n=2) -- THIN and DUST must never be counted,
    # proving the "restricted to the population each floor candidate can actually reach" fix.
    assert "| >=$1,000,000 | 2 |" in section
    # $100k-reachable adds THIN (n=3) but still excludes DUST (volume far below any floor).
    assert "| >=$100,000 | 3 |" in section
    # DUST's enormous half-spread must never leak into either restricted row's n or stats.
    assert "9000" not in section.split("## Restricted")[1].split("Flag")[0]


def test_floor_reachable_section_flat_5bp_comparison_is_informational_and_stricter():
    df = pd.DataFrame([
        _row("A/USD", 2_000_000.0, 20.0, 3.0),   # under its 20bp tier AND under flat 5bp
        _row("B/USD", 2_000_000.0, 20.0, 7.0),   # under its 20bp tier but ABOVE flat 5bp
    ])
    section = render_floor_reachable_section(df, floors=(1_000_000.0,))
    # n=2 reachable, 0 exceed the tiered 20bp assumption, 1 (B) exceeds the flat 5bp comparison.
    assert "| >=$1,000,000 | 2 | " in section
    row_line = [l for l in section.splitlines() if l.startswith("| >=$1,000,000")][0]
    cells = [c.strip() for c in row_line.strip("|").split("|")]
    # columns: floor, n, median, p90, max, n_exceed_tiered, %_tiered, n_exceed_flat, %_flat
    assert cells[5] == "0", f"no symbol should exceed its own tiered assumption here: {cells}"
    assert cells[7] == "1", f"exactly one symbol (B) should exceed the flat {FLAT_PRESET_BPS}bp comparison: {cells}"
    assert "informational only" in section, "the flat-5bp comparison must be clearly labeled informational, not a gate"


def test_floor_reachable_section_empty_population_reports_cleanly():
    df = pd.DataFrame([_row("DUST/USD", 1_000.0, 50.0, 9000.0)])
    section = render_floor_reachable_section(df, floors=(1_000_000.0,))
    assert "| >=$1,000,000 | 0 |" in section


def test_floor_reachable_section_flags_algo_and_xtz_by_name_when_present():
    df = pd.DataFrame([
        _row("ALGO/USD", 1_486_880.0, 20.0, 3.13),
        _row("XTZ/USD", 213_602.0, 50.0, 3.87),
        _row("BTC/USD", 191_105_354.0, 5.0, 0.01),
    ])
    section = render_floor_reachable_section(df, floors=(1_000_000.0,))
    assert "ALGO" in section and "XTZ" in section
    assert "BTC" not in section.split("Flag")[1] if "Flag" in section else True


def test_render_report_includes_the_floor_reachable_section():
    """render_report (the function the committed tiered_slippage_calibration.md is actually
    generated by) must include the new section automatically -- not something a caller has to
    remember to call separately."""
    df = pd.DataFrame([
        _row("BIG/USD", 50_000_000.0, 5.0, 1.0),
        _row("MID/USD", 2_000_000.0, 20.0, 3.0),
    ])
    report = render_report(df)
    assert "## Restricted to floor-candidate-reachable populations" in report
    assert "## By tier" in report, "the original headline section must still be present unchanged"
    assert "## Full per-symbol detail" in report


